#!/usr/bin/env python3
"""Qualify an every-physics-step contact-depth sensor without changing training.

This is a diagnostic, not a collision-proof certificate: it observes contacts
generated by MuJoCo at discrete steps. A depth violation can terminate an episode
after the current 25 Hz control block; it cannot prevent that block's motion.
"""

from assembly_policy.so101.limits import PENETRATION_LIMIT_M
import argparse
import hashlib
import json
import time
import xml.etree.ElementTree as ET
from pathlib import Path

import mujoco
from mujoco import rollout
import numpy as np

from assembly_policy.so101.env import STATE_SPEC, TASK_NAMES
from assembly_policy.so101.scene import ROOT, build_xml, load_plugin


SENSOR_NAME = 'min_contact_distance'
DOC = 'https://mujoco.readthedocs.io/en/3.17.0/XMLreference.html#sensor-contact'


def instrument(xml):
    """No match filters means all contacts, including constraint-excluded ones."""
    root = ET.fromstring(xml)
    sensor = root.find('sensor')
    if sensor is None:
        sensor = ET.SubElement(root, 'sensor')
    if any(s.get('name') == SENSOR_NAME for s in sensor):
        raise ValueError('Contact monitor already present')
    ET.SubElement(sensor, 'contact', name=SENSOR_NAME, data='dist', num='1', reduce='mindist')
    return ET.tostring(root, encoding='unicode')


def model_hash(m):
    binary = np.empty(mujoco.mj_sizeModel(m), np.uint8)
    mujoco.mj_saveModel(m, buffer=binary)
    return hashlib.sha256(binary.tobytes()).hexdigest()


def minimum_contact(d):
    return float(np.min(d.contact.dist)) if d.ncon else 0.


def sensor_address(m):
    sensor = m.sensor(SENSOR_NAME).id
    assert m.sensor_dim[sensor] == 1
    assert m.sensor_needstage[sensor] == mujoco.mjtStage.mjSTAGE_POS
    return int(m.sensor_adr[sensor])


def scratch_rollout(m, starts, controls, nthread):
    work = [mujoco.MjData(m) for _ in range(nthread)]
    with rollout.Rollout(nthread=nthread if nthread > 1 else 0) as engine:
        before = time.perf_counter()
        states, sensors = engine.rollout(m, work, starts, controls)
        wall = time.perf_counter() - before
    warnings = np.sum([d.warning.number for d in work], axis=0)
    return states, sensors, wall, warnings.tolist()


def representative_starts(directory):
    states, labels = [], []
    for task in TASK_NAMES:
        with np.load(directory / f'{task}_train.npz') as bank:
            families = bank['family']
            for family in np.unique(families):
                indices = np.flatnonzero(families == family)
                for index in indices[np.linspace(0, len(indices)-1, min(2, len(indices)), dtype=int)]:
                    states.append(bank['states'][index].copy())
                    labels.append(dict(task=task, family=int(family), index=int(index)))
    starts = np.asarray(states)
    starts[:, 0] = 0.
    return starts, labels


def sensor_audit(m, starts, states, controls, sensors):
    """Independent collision refresh at PRE-integration states, on separate data."""
    address = sensor_address(m)
    d = mujoco.MjData(m)
    errors, endpoint_minima = [], []
    worst = None
    for env in range(len(starts)):
        for step in range(states.shape[1]):
            previous = starts[env] if step == 0 else states[env, step-1]
            mujoco.mj_setState(m, d, previous, STATE_SPEC)
            d.ctrl[:] = controls[env, step]
            mujoco.mj_forward(m, d)
            contact_min = minimum_contact(d)
            error = abs(float(sensors[env, step, address]) - contact_min)
            errors.append(error)
            if worst is None or error > worst['error_m']:
                worst = dict(env=env, step=step, error_m=error,
                             sensor_m=float(sensors[env, step, address]), contact_m=contact_min)
        mujoco.mj_setState(m, d, states[env, -1], STATE_SPEC)
        d.ctrl[:] = controls[env, -1]
        mujoco.mj_forward(m, d)
        endpoint_minima.append(minimum_contact(d))
    return dict(samples=len(errors), max_error_m=max(errors), worst=worst,
                endpoint_minimum_distances_m=endpoint_minima)


def direct_step_timing(m, start, controls, count=160):
    """The contact array and dist sensor both describe the pre-integration pose."""
    d = mujoco.MjData(m)
    mujoco.mj_setState(m, d, start, STATE_SPEC)
    d.qacc_warmstart[:] = 0.
    address = sensor_address(m)
    errors = []
    for ctrl in controls[:count]:
        d.ctrl[:] = ctrl
        mujoco.mj_step(m, d)
        errors.append(abs(float(d.sensordata[address])-minimum_contact(d)))
    return dict(samples=len(errors), max_sensor_vs_existing_contact_error_m=max(errors),
                time_after_last_step_s=float(d.time))


def replay_policy(original, monitored, prefix, nthread, threshold):
    record = json.loads(prefix.with_suffix('.json').read_text())
    with np.load(prefix.with_suffix('.npz')) as z:
        initial = z['initial_state'].copy()
        recorded = z['states'].copy()
        controls = z['controls'].copy()
        audited_depth = z['penetration'].copy()
    if record['model_sha256'] != model_hash(original):
        raise ValueError('Policy archive uses a different model')
    for name, expected in record['plugin_sha256'].items():
        if hashlib.sha256((ROOT/'plugin/build'/name).read_bytes()).hexdigest() != expected:
            raise ValueError('Policy archive uses a different plugin')
    block = round(.04 / original.opt.timestep)
    if len(recorded) % block:
        raise ValueError('Expected complete 25 Hz controls in policy archive')
    state = initial[None].copy()
    collected, distances, endpoints, block_maxima = [], [], [], []
    data = [mujoco.MjData(monitored)]
    endpoint_data = mujoco.MjData(monitored)
    address = sensor_address(monitored)
    with rollout.Rollout(nthread=0) as engine:
        for start in range(0, len(recorded), block):
            command = controls[None, start:start+block]
            trace, sensor = engine.rollout(monitored, data, state, command)
            collected.append(trace[0].copy()); distances.append(sensor[0, :, address].copy())
            state = trace[:, -1].copy()
            # Existing env._refresh already performs this endpoint forward pass.
            mujoco.mj_setState(monitored, endpoint_data, state[0], STATE_SPEC)
            endpoint_data.ctrl[:] = command[0, -1]
            mujoco.mj_forward(monitored, endpoint_data)
            final_minimum = minimum_contact(endpoint_data)
            endpoints.append(final_minimum)
            block_maxima.append(max(0., -float(np.min(sensor[:, :, address])), -final_minimum))
    collected = np.concatenate(collected)
    distances = np.concatenate(distances)
    expected_previous_depth = np.r_[0., audited_depth[:-1]]
    # The archive's first depth is post-step; inspect the initial pose separately.
    mujoco.mj_setState(monitored, endpoint_data, initial, STATE_SPEC)
    endpoint_data.ctrl[:] = controls[0]
    mujoco.mj_forward(monitored, endpoint_data)
    expected_previous_depth[0] = max(0., -minimum_contact(endpoint_data))
    first = np.flatnonzero(np.asarray(block_maxima) > threshold)
    actual_first = np.flatnonzero(audited_depth > threshold)
    endpoint_boundary = None
    if len(actual_first):
        # End exactly at the first violating integrated pose. Its final sensor
        # describes the preceding pose; the endpoint check closes this gap.
        crossing = int(actual_first[0])
        block_start = crossing//block*block
        boundary_start = initial if block_start == 0 else recorded[block_start-1]
        command = controls[None, block_start:crossing+1]
        boundary_trace, boundary_sensor, _, _ = scratch_rollout(
            monitored, boundary_start[None], command, nthread)
        mujoco.mj_setState(monitored, endpoint_data, boundary_trace[0, -1], STATE_SPEC)
        endpoint_data.ctrl[:] = command[0, -1]
        mujoco.mj_forward(monitored, endpoint_data)
        endpoint_boundary = dict(
            full_state_bit_identical=np.array_equal(boundary_trace[0], recorded[block_start:crossing+1]),
            sensor_peak_penetration_m=max(0., -float(boundary_sensor[:, :, address].min())),
            endpoint_penetration_m=max(0., -minimum_contact(endpoint_data)),
            sensor_alone_would_miss=bool(np.min(boundary_sensor[:, :, address]) >= -threshold),
            endpoint_detects=minimum_contact(endpoint_data) < -threshold,
            steps=len(command[0]))
    return dict(
        policy_file=str(prefix), steps=len(recorded),
        full_state_bit_identical_to_archive=np.array_equal(collected, recorded),
        max_full_state_difference=float(np.max(np.abs(collected-recorded))),
        sensor_depth_vs_shifted_post_step_audit_max_error_m=float(np.max(np.abs(
            np.maximum(0., -distances)-expected_previous_depth))),
        max_sensor_penetration_m=max(0., -float(distances.min())),
        max_sensor_plus_endpoint_penetration_m=max(block_maxima),
        archived_max_penetration_m=float(audited_depth.max()),
        first_violating_physics_state_index=int(actual_first[0]) if len(actual_first) else None,
        first_guard_termination_control_index=int(first[0]) if len(first) else None,
        first_guard_termination_time_s=float((first[0]+1)*.04) if len(first) else None,
        archived_terminal=record.get('terminal'), original_control_count=len(recorded)//block,
        endpoint_minimum_distances_m=endpoints,
        block_max_penetration_m=block_maxima,
        last_integrated_state_boundary_test=endpoint_boundary,
        sensor_stage='Position: sensor[t] describes the pre-integration state; state[t] is post-integration.',
        sensor_forward_calls_per_control=0, endpoint_forward_calls_per_control=1,
        native_warning_counts=np.sum([d.warning.number for d in data], axis=0).tolist())


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--bank-dir', type=Path, default=ROOT/'data/so101/banks_near_v1')
    parser.add_argument('--policy-trace', type=Path, default=ROOT/'artifacts_local/policy_near_first')
    parser.add_argument('--out', type=Path, default=ROOT/'artifacts_local/contact_guard')
    parser.add_argument('--nthread', type=int, choices=(1, 2), default=2)
    parser.add_argument('--steps', type=int, default=160)
    parser.add_argument('--benchmark-repeats', type=int, default=5)
    parser.add_argument('--threshold', type=float, default=PENETRATION_LIMIT_M)
    args = parser.parse_args(); args.out.mkdir(parents=True, exist_ok=True)
    load_plugin(); xml = build_xml(); augmented = instrument(xml)
    original = mujoco.MjModel.from_xml_string(xml)
    monitored = mujoco.MjModel.from_xml_string(augmented)
    (args.out/'monitored.xml').write_text(augmented)
    starts, labels = representative_starts(args.bank_dir)
    rng = np.random.default_rng(8671)
    # Gentle nonzero robot controls plus all five predecessor configurations and
    # each available motor family. Policy replay separately exercises violation.
    targets = np.clip(starts[:, 1:13] + rng.uniform(-.003, .003, (len(starts), 12)),
                      original.actuator_ctrlrange[:, 0], original.actuator_ctrlrange[:, 1])
    controls = np.repeat(targets[:, None], args.steps, axis=1)
    baseline, _, base_wall, base_warnings = scratch_rollout(original, starts, controls, args.nthread)
    monitored_states, sensors, sensor_wall, sensor_warnings = scratch_rollout(monitored, starts, controls, args.nthread)
    parity = dict(full_state_bit_identical=np.array_equal(baseline, monitored_states),
                  max_full_state_difference=float(np.max(np.abs(baseline-monitored_states))),
                  qpos_bit_identical=np.array_equal(baseline[:, :, 1:1+original.nq], monitored_states[:, :, 1:1+original.nq]),
                  qvel_bit_identical=np.array_equal(baseline[:, :, 1+original.nq:], monitored_states[:, :, 1+original.nq:]),
                  finite=bool(np.isfinite(monitored_states).all() and np.isfinite(sensors).all()),
                  baseline_warning_counts=base_warnings, monitored_warning_counts=sensor_warnings)
    print('Parity:', parity, flush=True)
    audit = sensor_audit(monitored, starts, monitored_states, controls, sensors)
    print('Every-step independent audit:', audit['samples'], audit['max_error_m'], flush=True)
    direct = direct_step_timing(monitored, starts[-1], controls[-1])
    policy = replay_policy(original, monitored, args.policy_trace, args.nthread, args.threshold)
    print('Policy replay:', {k:v for k,v in policy.items() if not isinstance(v, list)}, flush=True)
    benchmark = []
    for repetition in range(args.benchmark_repeats):
        row = {}
        # Alternate order to limit systematic warm-cache/load bias. Both runs
        # always start from the same states with the same command sequence.
        order = [('baseline', original), ('sensor', monitored)]
        if repetition % 2: order.reverse()
        for name, model in order:
            trace, _, wall, warnings = scratch_rollout(model, starts, controls, args.nthread)
            row[name+'_wall_s'] = wall
            if not np.array_equal(trace, baseline) or any(warnings):
                raise AssertionError('Benchmark changed physics or reported a warning')
        row['sensor_over_baseline'] = row['sensor_wall_s']/row['baseline_wall_s']
        benchmark.append(row); print('Benchmark', repetition, row, flush=True)
    baseline_median = float(np.median([r['baseline_wall_s'] for r in benchmark]))
    sensor_median = float(np.median([r['sensor_wall_s'] for r in benchmark]))
    checks = dict(state_size_unchanged=mujoco.mj_stateSize(original, STATE_SPEC)==mujoco.mj_stateSize(monitored, STATE_SPEC),
                  complete_state_parity=parity['full_state_bit_identical'],
                  finite=parity['finite'], no_warnings=not any(base_warnings+sensor_warnings),
                  sensor_matches_every_contact_query=audit['max_error_m']==0.,
                  sensor_matches_step_contact_array=direct['max_sensor_vs_existing_contact_error_m']==0.,
                  archived_policy_exact=policy['full_state_bit_identical_to_archive'],
                  archived_audit_matches=policy['sensor_depth_vs_shifted_post_step_audit_max_error_m']==0.,
                  endpoint_closes_last_step_gap=bool(policy['last_integrated_state_boundary_test'] and
                      policy['last_integrated_state_boundary_test']['full_state_bit_identical'] and
                      policy['last_integrated_state_boundary_test']['sensor_alone_would_miss'] and
                      policy['last_integrated_state_boundary_test']['endpoint_detects']),
                  detects_archived_violation=policy['first_guard_termination_control_index'] is not None)
    report = dict(mujoco_version=mujoco.__version__, official_documentation=DOC,
                  qualification_script_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
                  production_edited=False, threshold_m=args.threshold,
                  original_model_sha256=model_hash(original), sensor_model_sha256=model_hash(monitored),
                  source_xml_sha256=hashlib.sha256(xml.encode()).hexdigest(),
                  sensor_xml_sha256=hashlib.sha256(augmented.encode()).hexdigest(),
                  sensor_xml='<contact name="min_contact_distance" data="dist" num="1" reduce="mindist"/>',
                  sensor_address=sensor_address(monitored), state_size=mujoco.mj_stateSize(monitored, STATE_SPEC),
                  original_sensor_count=original.nsensor, monitored_sensor_count=monitored.nsensor,
                  starts=labels, steps_per_start=args.steps, nthread=args.nthread,
                  parity=parity, contact_audit=audit, direct_step_timing=direct, policy_replay=policy,
                  benchmark=dict(rows=benchmark, baseline_median_s=baseline_median, sensor_median_s=sensor_median,
                                 median_time_ratio=sensor_median/baseline_median,
                                 added_seconds_per_25hz_env_control=(sensor_median-baseline_median)/(len(starts)*args.steps/80),
                                 concurrent_training=True, first_baseline_s=base_wall, first_sensor_s=sensor_wall),
                  checks=checks, passed=all(checks.values()),
                  integration='Combine max(0,-sensordata[:,:,address].min(axis=1)) with endpoint min contact distance after the existing _refresh; mark safety if depth exceeds threshold, then suppress success and reset. Reject nonfinite sensor data before PPO.',
                  limitation='Monitors generated discrete-step contacts only. Does not prove continuous nonintersection, catch omitted collision pairs, or stop inside an 80-step control block. Never represent a discarded violating block as physically acceptable.')
    (args.out/'report.json').write_text(json.dumps(report, indent=2)+'\n')
    np.savez_compressed(args.out/'parity.npz', starts=starts, controls=controls, baseline=baseline,
                        monitored=monitored_states, sensordata=sensors)
    print('PASS' if report['passed'] else 'FAIL', checks, flush=True)
    if not report['passed']: raise SystemExit(1)


if __name__ == '__main__':
    main()
